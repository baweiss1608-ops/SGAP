// Método para criptografar a senha
private String criptografarSenha(String senha) throws Exception {

    MessageDigest md = MessageDigest.getInstance("SHA-256");

    byte[] hash = md.digest(
        senha.getBytes(java.nio.charset.StandardCharsets.UTF_8)
    );

    StringBuilder resultado = new StringBuilder();

    for (byte b : hash) {
        resultado.append(String.format("%02x", b));
    }

    return resultado.toString();
}


// Método para converter o horário digitado para o formato Time
private Time converterHorario(String horario) {

    horario = horario.trim();

    // Caso o usuário digite somente HH:mm
    if (horario.length() == 5) {
        horario += ":00";
    }

    return Time.valueOf(horario);
}
