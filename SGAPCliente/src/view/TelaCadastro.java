    private void jButtonCadastrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonCadastrarActionPerformed
       boolean result = false;

    try {

        String crp = jTextFieldCrp.getText().trim();
        String cnpj = jTextFieldCnpj.getText().trim();
        String especialidade = jTextFieldEspecialidade.getText().trim();
        String contato = jTextFieldContato.getText().trim();
        String horarioInicioTexto = jTextFieldHorarioInicio.getText().trim();
        String horarioFinalTexto = jTextFieldHorarioFinal.getText().trim();
        String valorTexto = jTextFieldValor.getText().trim();
        String nome = jTextFieldNome.getText().trim();
        String email = jTextFieldEmail.getText().trim();
        String senha = new String(jPasswordFieldSenha.getPassword());

        // Verifica os campos obrigatórios
        if (crp.isEmpty() || cnpj.isEmpty() || especialidade.isEmpty()
                || contato.isEmpty() || horarioInicioTexto.isEmpty()
                || horarioFinalTexto.isEmpty() || valorTexto.isEmpty()
                || nome.isEmpty() || email.isEmpty()) {

            JOptionPane.showMessageDialog(this,
                    "Preencha todos os campos!");

            return;
        }

        // Converte os horários
        Time horarioInicial = converterHorario(horarioInicioTexto);
        Time horarioFinal = converterHorario(horarioFinalTexto);

        // Converte o valor
        float valor = Float.parseFloat(valorTexto.replace(",", "."));

        String senhaCriptografada;

        // Se estiver editando e não digitar uma nova senha,
        // mantém a senha atual.
        if (psicologo != null && senha.isEmpty()) {

            senhaCriptografada = psicologo.getSenha();

        } else {

            if (senha.isEmpty()) {
                JOptionPane.showMessageDialog(this,
                        "Preencha a senha!");

                jPasswordFieldSenha.requestFocus();
                return;
            }

            senhaCriptografada = criptografarSenha(senha);
        }

        // Edição de psicólogo
        if (psicologo != null) {

            Psicologo psicologoEditar = new Psicologo(
                    psicologo.getCodPsicologo(),
                    crp,
                    nome,
                    contato,
                    cnpj,
                    email,
                    senhaCriptografada,
                    especialidade,
                    horarioInicial,
                    horarioFinal,
                    valor
            );

            result = Principal.ccont.psicologoEditar(psicologoEditar);

        } else {

            // Cadastro de novo psicólogo
            Psicologo psicologoInserir = new Psicologo(
                    crp,
                    nome,
                    contato,
                    cnpj,
                    email,
                    senhaCriptografada,
                    especialidade,
                    horarioInicial,
                    horarioFinal,
                    valor
            );

            result = Principal.ccont.psicologoInserir(psicologoInserir);
        }

    } catch (NumberFormatException e) {

        JOptionPane.showMessageDialog(this,
                "Informe um valor válido para a consulta!");

        jTextFieldValor.requestFocus();
        return;

    } catch (IllegalArgumentException e) {

        JOptionPane.showMessageDialog(this,
                "Informe os horários no formato HH:mm ou HH:mm:ss!");

        return;

    } catch (Exception e) {

        e.printStackTrace();

        JOptionPane.showMessageDialog(this,
                "Erro interno: " + e.getMessage());

        return;
    }

   if (result) {

    JOptionPane.showMessageDialog(this,
            "Cadastro realizado com sucesso!");

    TelaLogin telaLogin = new TelaLogin();
    telaLogin.setVisible(true);

    dispose();

} else {

    JOptionPane.showMessageDialog(this,
            "Erro ao cadastrar ou editar psicólogo!");
}
        
    }//GEN-LAST:event_jButtonCadastrarActionPerformed

